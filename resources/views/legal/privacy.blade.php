    <p>Vestu is a marketplace for dancewear sale and hire. We collect and use personal data only where needed to provide accounts, listings, messaging, checkout, payments, delivery, safety, support, and legal compliance.</p>

    <h2>Data We Collect</h2>
    <ul>
        <li>Account details, including name, email address, profile information, and login tokens.</li>
        <li>Listing and transaction information, including product details, prices, fulfilment choices, order history, seller status, and dispute records.</li>
        <li>Messages, reviews, favourites, notifications, and support communications.</li>
        <li>Addresses used for billing, shipping, collection, and drop off.</li>
        <li>Uploaded product images and files needed to operate the marketplace.</li>
        <li>Payment and payout information processed through Stripe Connect. Vestu does not store full card numbers.</li>
    </ul>

    <h2>How We Use Data</h2>
    <ul>
        <li>To create and manage user accounts.</li>
        <li>To publish listings, process orders, calculate fees, manage deposits, and release seller payouts.</li>
        <li>To provide buyer and seller messaging, notifications, reviews, and customer support.</li>
        <li>To prevent fraud, secure the service, investigate disputes, and meet legal obligations.</li>
        <li>To maintain service logs, backups, and operational records.</li>
    </ul>

    <h2>Third Party Recipients</h2>
    <p>We use service providers where required to operate the marketplace, including Stripe for payments and seller onboarding, DigitalOcean or compatible object storage for hosting and uploaded media, and email providers such as Mailgun or SendGrid for transactional email. These providers process data under their own security and privacy controls.</p>

    <h2>Uploads And Visibility</h2>
    <p>Product images uploaded for marketplace listings may be publicly accessible so buyers can view listings. Private account data, payment data, and internal records should not be uploaded as listing media.</p>

    <h2>Retention And Deletion</h2>
    <p>We retain data while accounts are active and for as long as needed for orders, disputes, fraud prevention, tax, accounting, and legal duties. Users can request account deletion from the app, though some transaction records may need to be retained.</p>

