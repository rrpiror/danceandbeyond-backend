    <p>Where UK GDPR or similar privacy laws apply, we process personal data under the following lawful bases:</p>
    <ul>
        <li><strong>Contract:</strong> to provide accounts, listings, orders, hire bookings, payments, delivery and support.</li>
        <li><strong>Legitimate interests:</strong> to secure the service, prevent fraud, resolve disputes, maintain records, improve functionality and operate the marketplace.</li>
        <li><strong>Legal obligation:</strong> to comply with tax, accounting, regulatory, payment, consumer protection and law enforcement obligations.</li>
        <li><strong>Consent:</strong> where we ask for permission, such as optional marketing communications or device permissions.</li>
    </ul>

