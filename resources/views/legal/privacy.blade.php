        <li><strong>Stripe:</strong> Stripe and Stripe Connect process payments, seller onboarding, identity verification, fraud checks, refunds, deposits, transfers and payouts.</li>
        <li><strong>Hosting and storage providers:</strong> we use providers such as DigitalOcean and compatible storage services to host the app backend, website, database, logs and uploaded media.</li>
        <li><strong>Email and notification providers:</strong> we use service providers to send account, password reset, order, support and service messages.</li>
        <li><strong>Professional and legal advisers:</strong> we may share data with advisers, insurers, auditors, regulators or law enforcement where necessary.</li>
        <li><strong>Business transfer:</strong> data may be transferred if Vestu is involved in a merger, acquisition, restructuring or sale of assets.</li>
    </ul>

