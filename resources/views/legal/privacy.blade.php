    <h1>Privacy Policy</h1>
    <p class="muted">Last updated: 1 September 2026</p>

    <p>This Privacy Policy explains how Dance and Beyond trading as Vestu ("Vestu", "we", "us" and "our") collects, uses and shares personal data when you use the Vestu mobile application, website, marketplace, payment flows, messaging features, support channels and related services.</p>
    <p>For privacy questions or requests, contact us at <a href="mailto:hello@vestu.co.uk">hello@vestu.co.uk</a>.</p>

    <h2>1. Who We Are</h2>
    <p>Dance and Beyond trading as Vestu is the controller of personal data collected through Vestu, except where a third party such as Stripe acts as an independent controller for its own payment, identity verification, fraud prevention and compliance processing.</p>

    <h2>2. Personal Data We Collect</h2>
    <h3>Account and profile data</h3>
    <p>We collect information used to create and manage an account, including name, email address, password credentials, account type, profile photo, profile details, user ID, login tokens and account settings.</p>

    <h3>Address and fulfilment data</h3>
    <p>We collect billing, shipping, collection and drop-off addresses, including house number, building name, street, town, city and postcode. Address data is used to support checkout, delivery, collection, seller fulfilment, account profile features and order records.</p>

    <h3>Listing and marketplace data</h3>
    <p>When you list an item, we collect product names, descriptions, categories, brands, conditions, prices, colours, sizes, quantities, stock levels, delivery charges, fulfilment options, hire periods, unavailable dates, deposits, late return fees and uploaded photos or videos.</p>

    <h3>Order, hire and payment data</h3>
    <p>We collect order history, basket contents, hire date ranges, order statuses, cancellation records, return statuses, delivery confirmations, seller order records, transaction values, platform fees, delivery charges, deposits, late return fees, refunds and dispute information.</p>
    <p>Payments and seller payouts are processed using Stripe and Stripe Connect. Vestu does not store full payment card numbers. Stripe may collect payment method details, bank account details, identity verification information and compliance information directly from you.</p>

    <h3>Messages, reviews and support</h3>
    <p>We collect messages sent between buyers and sellers, chat records, reviews, favourites, notifications, customer support requests and related correspondence.</p>

    <h3>Technical and usage data</h3>
    <p>We collect technical data needed to operate and protect the service, including IP address, device and app information, server logs, security logs, error logs, crash information, performance information and records of how users interact with the app and website.</p>

    <h2>3. How We Use Personal Data</h2>
    <ul>
        <li>To create, authenticate and manage user accounts.</li>
        <li>To provide marketplace features for buying, selling and hiring dancewear.</li>
        <li>To publish and display listings, uploaded media, prices, stock and availability.</li>
        <li>To process baskets, checkout, orders, hire bookings, delivery charges, refunds, deposits and payouts.</li>
        <li>To enable buyer and seller communication, order updates, notifications and support.</li>
        <li>To manage seller onboarding, Stripe Connect status, payment confirmations, transfers and compliance checks.</li>
        <li>To prevent fraud, protect accounts, enforce our terms and investigate disputes.</li>
        <li>To maintain, debug, secure and improve the app, website and backend systems.</li>
        <li>To comply with legal, tax, accounting, regulatory and platform obligations.</li>
    </ul>

